  function urDigits(s) {
    return String(s).replace(/[0-9]/g, function (d) { return UR_DIGITS[d]; });
  }

  function arDigits(s) {
    return String(s).replace(/[0-9]/g, function (d) { return AR_DIGITS[d]; });
  }

  function digits(s) {
    const lang = get();
    if (lang === 'ur') return urDigits(s);
    if (lang === 'ar') return arDigits(s);
    return String(s);
  }

  function get() { try { return localStorage.getItem('mdm_lang') || 'en'; } catch (e) { return 'en'; } }

  function set(lang) {
    try { localStorage.setItem('mdm_lang', lang); } catch (e) {}
    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', (lang === 'ur' || lang === 'ar') ? 'rtl' : 'ltr');
  }

  function t(key) {
    const lang = get();
    const table = dict[lang] || dict.en;
    return table[key] !== undefined ? table[key] : (dict.en[key] !== undefined ? dict.en[key] : key);
  }

